//! Rust bindings for libgodot: Godot Engine embedded as a library.
//!
//! [`GodotInstance`] is the safe entry point; [`sys`] has the raw FFI it is
//! built on. See the README for how the engine is found, built and linked.

/// Raw bindings to `libgodot.h` and the GDExtension interface, generated by
/// bindgen from the engine source the crate was built against.
#[allow(warnings)]
pub mod sys {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

mod instance;

pub use instance::{Error, GodotInstance};
// Older code reached the raw API from the crate root.
pub use sys::*;

/// How the engine was linked: "static", "dynamic" or "none".
pub const LINKAGE: &str = env!("GODOT_LINKAGE");
